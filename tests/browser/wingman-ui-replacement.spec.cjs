const {test,expect}=require('@playwright/test');
const frame=page=>page.frameLocator('#wingman-new-interface iframe');
test('illustrated home and operations replace the old visible menus',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.locator('#wingman-new-interface')).toBeVisible();
 await expect(frame(page).locator('.v4-home')).toBeVisible();
 await expect(frame(page).locator('.home-wordmark')).toHaveText('WINGMAN');
 const bg=await frame(page).locator('.v4-home').evaluate(el=>getComputedStyle(el).backgroundImage);
 expect(bg).toContain('data:image/webp;base64');
 await frame(page).locator('[data-action="operations"]').click();
 await expect(frame(page).locator('.operation-ref')).toHaveCount(5);
 await frame(page).locator('[data-op="3"]').click();
 await frame(page).locator('[data-action="operations-next"]').click();
 await expect(frame(page).locator('.grid-plane-card')).toHaveCount(3);
 expect(errors).toEqual([]);
});
test('arcade fighter choice launches original game, with return to new home',async({page})=>{
 await page.goto('/');
 await frame(page).locator('[data-action="aircraft"]').click();
 await frame(page).locator('[data-faction="Axis"]').click();
 await frame(page).locator('[data-plane="4"]').click();
 await expect(frame(page).locator('.grid-plane-card.selected')).toContainText('BF 110');
 await frame(page).locator('[data-action="launch-arcade"]').click();
 await expect(page.locator('#wingman-new-interface')).toBeHidden();
 await expect(page.locator('#menu')).toHaveClass(/hidden/);
 await expect(page.locator('#menu-return')).toBeVisible();
 await page.locator('#menu-return').click();
 await expect(page.locator('#wingman-new-interface')).toBeVisible();
});
test('career uses actual roster, creates save, shows rival branches and launches chosen aircraft',async({page})=>{
 await page.goto('/');
 await frame(page).locator('[data-action="career"]').click();
 await expect(frame(page).locator('.career-intro-layout')).toBeVisible();
 await frame(page).locator('[data-action="to-pilots"]').click();
 await expect(frame(page).locator('.pilot-card')).toHaveCount(6);
 await frame(page).locator('[data-action="confirm-pilot"]').click();
 await expect(frame(page).locator('[data-action="begin-career"]')).toBeVisible();
 const p=await page.evaluate(()=>JSON.parse(localStorage.getItem('wingman-road-to-ace-v1')));
 expect(p.profile.rosterId).toMatch(/^ace-/);
 await frame(page).locator('[data-action="begin-career"]').click();
 await expect(frame(page).locator('.career-route')).toHaveCount(3);
 await frame(page).locator('[data-choice="1"]').click();
 await frame(page).locator('[data-action="career-aircraft"]').click();
 await expect(frame(page).locator('.grid-plane-card')).toHaveCount(3);
 await frame(page).locator('[data-plane="1"]').click();
 await frame(page).locator('[data-action="launch-career"]').click();
 await expect(page.locator('#wingman-new-interface')).toBeHidden();
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('wingman-road-to-ace-v1')));
 expect(saved.run.aircraft).toBe('heavy');
});
